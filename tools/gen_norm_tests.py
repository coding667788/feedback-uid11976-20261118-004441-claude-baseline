BODY = r'''
class NormalizationRulesTest(unittest.TestCase):
    # ------------------------------------------------------------- raw rejects
    def test_empty_string_rejected_in_both_policies(self):
        for policy in (V1, V2):
            with self.assertRaises(InvalidLogin) as ctx:
                normalize("", policy)
            self.assertEqual(ctx.exception.details["reason"], "empty")

    def test_whitespace_characters_rejected(self):
        samples = [
            " a",
            "a\t",
            "a\nb",
            "a" + NNBSP + "b",
            "a" + OGHAM + "b",
            IDEO_SPACE + "x",
        ]
        for raw in samples:
            self.assertTrue(any(ch.isspace() for ch in raw))
            for policy in (V1, V2):
                with self.subTest(raw=raw, policy=policy):
                    with self.assertRaises(InvalidLogin) as ctx:
                        normalize(raw, policy)
                    self.assertEqual(ctx.exception.details["reason"], "whitespace")

    def test_control_format_categories_rejected(self):
        samples = [
            ("a" + NUL + "b", "Cc"),
            ("a" + BACKSPACE + "b", "Cc"),
            ("a" + SOFT_HYPHEN + "b", "Cf"),
            ("a" + DELETE + "b", "Cc"),
            ("a" + RLM + "b", "Cf"),
            ("a" + MVS + "b", "Cf"),
        ]
        for raw, expected_cat in samples:
            self.assertEqual(category(raw[1]), expected_cat)
            for policy in (V1, V2):
                with self.subTest(raw=raw, policy=policy):
                    with self.assertRaises(InvalidLogin) as ctx:
                        normalize(raw, policy)
                    self.assertEqual(
                        ctx.exception.details["reason"], "forbidden_category"
                    )

    def test_lone_surrogate_rejected(self):
        raw = "x" + SURROGATE
        self.assertEqual(category(raw[1]), "Cs")
        for policy in (V1, V2):
            with self.assertRaises(InvalidLogin) as ctx:
                normalize(raw, policy)
            self.assertEqual(ctx.exception.details["reason"], "forbidden_category")

    def test_normalized_stage_also_validated(self):
        # U+00A8 DIAERESIS is raw-valid (category Sk, no whitespace) but
        # NFKC expands it to SPACE + combining diaeresis, so only V2 fails
        # and only the normalized-stage check catches it. V1 keeps the
        # character as-is and must accept it.
        self.assertEqual(ud_normalize("NFKC", DIAERESIS), " " + chr(0x0308))
        self.assertEqual(normalize(DIAERESIS, V1), DIAERESIS)
        with self.assertRaises(InvalidLogin) as ctx:
            normalize(DIAERESIS, V2)
        self.assertEqual(ctx.exception.details["stage"], "normalized")
        self.assertEqual(ctx.exception.details["reason"], "whitespace")

    def test_utf8_byte_limit_on_normalized_result(self):
        self.assertEqual(normalize("a" * 128, V1), "a" * 128)
        with self.assertRaises(InvalidLogin) as ctx:
            normalize("a" * 129, V1)
        self.assertEqual(ctx.exception.details["reason"], "too_long")
        self.assertEqual(ctx.exception.details["utf8_bytes"], 129)

    def test_byte_limit_counts_utf8_not_codepoints(self):
        raw = E_ACUTE * 43  # 2 bytes each -> 86 bytes, still legal
        self.assertEqual(len(raw), 43)
        self.assertEqual(len(raw.encode("utf-8")), 86)
        raw_long = E_ACUTE * 65  # 130 bytes -> rejected
        self.assertEqual(len(raw_long.encode("utf-8")), 130)
        with self.assertRaises(InvalidLogin):
            normalize(raw_long, V1)
        self.assertEqual(normalize(E_ACUTE * 42, V1), E_ACUTE * 42)

    def test_v2_expansion_can_make_v1_valid_name_too_long(self):
        # U+0130: V1 NFC = 2 bytes/cp; V2 folds to 'i' + U+0307 = 3 bytes/cp.
        raw = CAPITAL_I_DOT * 43
        self.assertEqual(len(normalize(raw, V1).encode("utf-8")), 86)
        with self.assertRaises(InvalidLogin) as ctx:
            normalize(raw, V2)
        self.assertEqual(ctx.exception.details["stage"], "normalized")
        self.assertEqual(ctx.exception.details["reason"], "too_long")

    # ------------------------------------------------------------- V1 behavior
    def test_v1_is_nfc_case_sensitive(self):
        self.assertEqual(normalize(E_DECOMP, V1), E_ACUTE)
        self.assertEqual(normalize("John", V1), "John")
        self.assertNotEqual(normalize("John", V1), normalize("john", V1))

    def test_v1_distinguishes_full_width_and_half_width(self):
        self.assertNotEqual(normalize("ABC123", V1), normalize(FULLWIDTH, V1))

    # ------------------------------------------------------------- V2 behavior
    def test_v2_is_nfkc_casefold_nfkc(self):
        expected = ud_normalize(
            "NFKC", ud_normalize("NFKC", FULLWIDTH).casefold()
        )
        self.assertEqual(normalize(FULLWIDTH, V2), expected)
        self.assertEqual(normalize(FULLWIDTH, V2), "abc123")

    def test_v2_full_half_width_collision(self):
        self.assertEqual(normalize("ABC123", V2), normalize(FULLWIDTH, V2))

    def test_v2_casefold_expansion(self):
        self.assertEqual(normalize("Stra" + SHARP_S + "e", V2), "strasse")
        self.assertEqual(normalize("STRASSE", V2), "strasse")
        word1 = CAPITAL_SIGMA + "O" + CAPITAL_SIGMA
        word2 = SMALL_SIGMA + "o" + SMALL_SIGMA
        word3 = SMALL_SIGMA + "o" + LUNATE_SIGMA
        self.assertEqual(normalize(word1, V2), normalize(word2, V2))
        self.assertEqual(normalize(word1, V2), normalize(word3, V2))

    def test_v2_composed_and_decomposed_collide(self):
        self.assertNotEqual(E_ACUTE, E_DECOMP)
        self.assertEqual(normalize(E_ACUTE, V2), normalize(E_DECOMP, V2))

    def test_v2_keeps_v1_distinct_collapsed(self):
        self.assertNotEqual(normalize("John", V1), normalize("john", V1))
        self.assertEqual(normalize("John", V2), normalize("john", V2))

    def test_no_whitespace_stripping_or_visual_substitution(self):
        with self.assertRaises(InvalidLogin):
            normalize("  john  ", V2)
        # Cyrillic 'a' has no compatibility mapping to Latin 'a'.
        self.assertNotEqual(
            normalize("paypal", V2), normalize("p" + CYR_A + "ypal", V2)
        )

    def test_unknown_policy_rejected(self):
        with self.assertRaises(ValueError):
            normalize("x", "V9")

    def test_non_string_rejected(self):
        with self.assertRaises(InvalidLogin):
            normalize(123, V1)  # type: ignore[arg-type]


if __name__ == "__main__":
    unittest.main(verbosity=2)
'''


